package reto1;

public class funciones2 {

    public static boolean esPar(int n) {
        return n % 2 == 0;
    }

    public static boolean esImpar(int n) {
        return n % 2 != 0;
    }

    public static boolean esPositivo(int n) {
        return n >= 0;
    }

    public static boolean esNegativo(int n) {
        return n < 0;
    }
}